-- Nhận thưởng chỉ khi tiến độ đủ; đánh dấu đã nhận và cộng tiền trong cùng giao dịch.
CREATE OR REPLACE FUNCTION public.claim_quest_reward(p_quest_id BIGINT)
RETURNS JSONB
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path = public
AS $$
DECLARE
  quest_row public.nhiem_vu%ROWTYPE;
  user_quest_row public.nhiem_vu_nguoi_dung%ROWTYPE;
  new_balance INTEGER;
  now_ms BIGINT := FLOOR(EXTRACT(EPOCH FROM now()) * 1000);
BEGIN
  IF auth.uid() IS NULL OR NOT public.is_current_user_active() THEN
    RAISE EXCEPTION 'Active account required' USING ERRCODE = '42501';
  END IF;

  SELECT * INTO quest_row FROM public.nhiem_vu
   WHERE id = p_quest_id AND is_active = 1
     AND starts_at <= now_ms AND ends_at >= now_ms;
  IF NOT FOUND THEN RETURN jsonb_build_object('claimed', false); END IF;
  IF quest_row.reward < 0 OR quest_row.reward > 100000 THEN
    RETURN jsonb_build_object('claimed', false);
  END IF;

  SELECT * INTO user_quest_row FROM public.nhiem_vu_nguoi_dung
   WHERE user_id = auth.uid() AND quest_id = p_quest_id
   FOR UPDATE;
  IF NOT FOUND OR user_quest_row.claimed <> 0
     OR user_quest_row.progress < quest_row.goal_value THEN
    RETURN jsonb_build_object('claimed', false);
  END IF;

  UPDATE public.nhiem_vu_nguoi_dung SET claimed = 1
   WHERE user_id = auth.uid() AND quest_id = p_quest_id;
  PERFORM set_config('novelreader.allow_economy_update', 'true', true);
  UPDATE public.ho_so SET linh_thach = LEAST(9999999, linh_thach + quest_row.reward)
   WHERE id = auth.uid() RETURNING linh_thach INTO new_balance;
  IF NOT FOUND THEN RAISE EXCEPTION 'Profile not found'; END IF;

  RETURN jsonb_build_object(
    'claimed', true,
    'reward', quest_row.reward,
    'balance', new_balance
  );
END;
$$;

