-- Tự cập nhật điểm trung bình khi người dùng đánh giá, không cần cấp quyền sửa
-- trực tiếp bảng truyện cho mọi độc giả.
CREATE OR REPLACE FUNCTION public.refresh_novel_rating()
RETURNS TRIGGER
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path = public
AS $$
DECLARE
  affected_novel_id BIGINT;
BEGIN
  affected_novel_id := CASE WHEN TG_OP = 'DELETE' THEN OLD.novel_id ELSE NEW.novel_id END;
  UPDATE public.truyen
     SET rating = COALESCE((SELECT ROUND(AVG(stars)::numeric, 1)
                              FROM public.danh_gia WHERE novel_id = affected_novel_id), 0)
   WHERE id = affected_novel_id;
  IF TG_OP = 'DELETE' THEN RETURN OLD; END IF;
  RETURN NEW;
END;
$$;

DROP TRIGGER IF EXISTS refresh_novel_rating_after_change ON public.danh_gia;
CREATE TRIGGER refresh_novel_rating_after_change
AFTER INSERT OR UPDATE OR DELETE ON public.danh_gia
FOR EACH ROW EXECUTE FUNCTION public.refresh_novel_rating();

-- Tự ẩn bình luận sau đủ ba báo cáo đang mở, kể cả khi báo cáo đến từ thiết bị khác.
CREATE OR REPLACE FUNCTION public.hide_comment_after_reports()
RETURNS TRIGGER
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path = public
AS $$
BEGIN
  IF NEW.target_type = 'comment' THEN
    UPDATE public.binh_luan
       SET is_hidden = 1
     WHERE id = NEW.target_id
       AND (SELECT COUNT(*) FROM public.bao_cao
             WHERE target_type = 'comment'
               AND target_id = NEW.target_id
               AND status = 'open') >= 3;
  END IF;
  RETURN NEW;
END;
$$;

DROP TRIGGER IF EXISTS hide_comment_after_reports_trigger ON public.bao_cao;
CREATE TRIGGER hide_comment_after_reports_trigger
AFTER INSERT OR UPDATE OF status ON public.bao_cao
FOR EACH ROW EXECUTE FUNCTION public.hide_comment_after_reports();

