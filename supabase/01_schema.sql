  END IF;

  SELECT COALESCE(jsonb_agg(jsonb_build_object(
    'chapter_id', c.id,
    'chapter_index', c.chapter_index,
    'title', c.title,
    'readers_count', COALESCE(r.readers_count, 0)
  ) ORDER BY c.chapter_index), '[]'::jsonb)
  INTO result
  FROM public.chuong c
  LEFT JOIN (
    SELECT chapter_id, COUNT(DISTINCT user_id)::INTEGER AS readers_count
    FROM public.nhat_ky_phien_doc
    WHERE novel_id = p_novel_id
    GROUP BY chapter_id
  ) r ON r.chapter_id = c.id
  WHERE c.novel_id = p_novel_id;

  RETURN result;
END;
$$;

