-- Chính sách quản trị dùng SECURITY DEFINER để kiểm tra role mà không tạo vòng RLS.
CREATE OR REPLACE FUNCTION public.is_current_user_admin()
RETURNS BOOLEAN
LANGUAGE SQL
STABLE
SECURITY DEFINER
SET search_path = public
AS $$
  SELECT EXISTS (
    SELECT 1 FROM public.ho_so
    WHERE id = auth.uid() AND role = 'admin' AND status = 'active'
  );
$$;

REVOKE ALL ON FUNCTION public.is_current_user_admin() FROM PUBLIC;
GRANT EXECUTE ON FUNCTION public.is_current_user_admin() TO anon, authenticated;

CREATE OR REPLACE FUNCTION public.is_current_user_active()
RETURNS BOOLEAN
LANGUAGE SQL
STABLE
SECURITY DEFINER
SET search_path = public
AS $$
  SELECT EXISTS (
    SELECT 1 FROM public.ho_so
    WHERE id = auth.uid() AND (
      status = 'active'
      OR (status = 'banned' AND ban_until IS NOT NULL
          AND ban_until <= FLOOR(EXTRACT(EPOCH FROM now()) * 1000))
    )
  );
$$;

REVOKE ALL ON FUNCTION public.is_current_user_active() FROM PUBLIC;
GRANT EXECUTE ON FUNCTION public.is_current_user_active() TO authenticated;

-- Metrics tổng hợp ẩn danh để dashboard admin không phải đọc lịch sử của từng user.
CREATE OR REPLACE FUNCTION public.admin_dashboard_metrics(p_days INTEGER DEFAULT 30)
RETURNS JSONB
LANGUAGE plpgsql
STABLE
SECURITY DEFINER
SET search_path = public
AS $$
DECLARE
  days_count INTEGER := LEAST(90, GREATEST(7, COALESCE(p_days, 30)));
  today_start BIGINT := FLOOR(EXTRACT(EPOCH FROM date_trunc('day', now())) * 1000);
  result JSONB;
BEGIN
  IF NOT public.is_current_user_admin() THEN
    RAISE EXCEPTION 'Admin access required' USING ERRCODE = '42501';
  END IF;

  SELECT jsonb_build_object(
    'total_users', (SELECT COUNT(*) FROM public.ho_so),
    'dau', (SELECT COUNT(*) FROM public.ho_so WHERE last_active_at >= today_start),
    'wau', (SELECT COUNT(*) FROM public.ho_so WHERE last_active_at >= today_start - 7 * 86400000),
    'total_novels', (SELECT COUNT(*) FROM public.truyen WHERE deleted_at IS NULL),
    'views_today', (SELECT COUNT(*) FROM public.nhat_ky_phien_doc WHERE started_at >= today_start),
    'daily', COALESCE((
      SELECT jsonb_agg(jsonb_build_object(
        'date_key', to_char(day::date, 'YYYY-MM-DD'),
        'words_read', COALESCE(s.words_read, 0),
        'minutes_read', COALESCE(s.minutes_read, 0)
      ) ORDER BY day)
      FROM generate_series(current_date - (days_count - 1), current_date, interval '1 day') AS day
      LEFT JOIN LATERAL (
        SELECT SUM(words_read)::BIGINT AS words_read, SUM(minutes_read)::BIGINT AS minutes_read
          FROM public.phien_doc p
         WHERE p.date_key = to_char(day::date, 'YYYY-MM-DD')
      ) s ON TRUE
    ), '[]'::jsonb),
    'heatmap', COALESCE((
      SELECT jsonb_agg(jsonb_build_object('weekday', weekday, 'hour', hour, 'sessions', sessions))
        FROM (
          SELECT EXTRACT(ISODOW FROM to_timestamp(started_at / 1000.0))::INTEGER - 1 AS weekday,
                 hour_of_day AS hour,
                 COUNT(*)::INTEGER AS sessions
            FROM public.nhat_ky_phien_doc
           WHERE started_at >= today_start - 7 * 86400000
           GROUP BY 1, 2
        ) h
    ), '[]'::jsonb)
  ) INTO result;
  RETURN result;
END;
$$;

REVOKE ALL ON FUNCTION public.admin_dashboard_metrics(INTEGER) FROM PUBLIC;
GRANT EXECUTE ON FUNCTION public.admin_dashboard_metrics(INTEGER) TO authenticated;

-- Số độc giả duy nhất đã có phiên đọc ở từng chương của một truyện.
